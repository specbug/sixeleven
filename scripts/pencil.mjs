// Draws the red-pencil strokes that sit under links and writes them to app/pencil.css.
//   node scripts/pencil.mjs
//
// Each stroke is a filled polygon along a gently wavering centreline: it lands heavy and
// lifts into a long thin tail, the way a hand moves left to right. Thickness wavers
// between about 0.9 and 1.8px, the centreline wobbles less than 0.4px, and the tips taper
// almost to nothing. The SVG stretches to each link's width (preserveAspectRatio none),
// so thickness stays true while the tapers scale with the link. Four variants; links pick
// one from a hash of their URL (see lib/pencil.ts). Each has a rest state at 90% and a
// hover state 35% thicker at full strength, in the light and dark cinnabar.
import { writeFileSync } from "node:fs"

const H = 5 // px height of the background box; the stroke is centred in it
const W = 200 // viewBox width; stretched to the link
const N = 48 // samples along the stroke

const CINNABAR = { light: [0.56, 0.2, 30], dark: [0.68, 0.17, 32] }
const SEEDS = [23, 11, 51, 37]
const STROKE = { tMin: 0.9, tMax: 1.8, taperL: 0.035, taperR: 0.4, wobble: 0.2, tilt: 0.3, tip: 0.1 }

function oklchToHex([L, C, h]) {
  const a = C * Math.cos((h * Math.PI) / 180)
  const b = C * Math.sin((h * Math.PI) / 180)
  const l = (L + 0.3963377774 * a + 0.2158037573 * b) ** 3
  const m = (L - 0.1055613458 * a - 0.0638541728 * b) ** 3
  const s = (L - 0.0894841775 * a - 1.291485548 * b) ** 3
  const rgb = [
    4.0767416621 * l - 3.3077115913 * m + 0.2309699292 * s,
    -1.2684380046 * l + 2.6097574011 * m - 0.3413193965 * s,
    -0.0041960863 * l - 0.7034186147 * m + 1.707614701 * s,
  ]
  return (
    "#" +
    rgb
      .map((x) => {
        x = Math.min(1, Math.max(0, x))
        x = x <= 0.0031308 ? 12.92 * x : 1.055 * x ** (1 / 2.4) - 0.055
        return Math.round(x * 255).toString(16).padStart(2, "0")
      })
      .join("")
  )
}

function random(seed) {
  let s = seed >>> 0
  return () => ((s = (s * 1664525 + 1013904223) >>> 0) / 4294967296)
}

const smooth = (t) => (t <= 0 ? 0 : t >= 1 ? 1 : t * t * (3 - 2 * t))

function path(seed, scale) {
  const r = random(seed)
  const phase = [r() * 6.28, r() * 6.28, r() * 6.28]
  const freq = [0.6 + r() * 0.8, 1.6 + r() * 1.4, 0.3 + r() * 0.5]
  const top = []
  const bottom = []
  for (let i = 0; i <= N; i++) {
    const u = i / N
    const wobble = STROKE.wobble * (0.6 * Math.sin(phase[0] + u * freq[0] * 6.28) + 0.4 * Math.sin(phase[1] + u * freq[1] * 6.28))
    const y = H / 2 + STROKE.tilt * (0.5 - u) + wobble
    const pressure = 0.5 + 0.5 * Math.sin(phase[2] + u * freq[2] * 6.28)
    const weight = 0.75 * (1 - u) ** 0.7 + 0.25 * pressure
    const taper = Math.min(smooth(u / STROKE.taperL), smooth((1 - u) / STROKE.taperR))
    const t = (STROKE.tMin + (STROKE.tMax - STROKE.tMin) * weight) * (STROKE.tip + (1 - STROKE.tip) * taper) * scale
    const x = (u * W).toFixed(1)
    top.push(`${x} ${(y - t / 2).toFixed(2)}`)
    bottom.unshift(`${x} ${(y + t / 2).toFixed(2)}`)
  }
  return `M${top.concat(bottom).join("L")}Z`
}

const uri = (d, color, opacity) =>
  `url("data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='0 0 ${W} ${H}' preserveAspectRatio='none'><path d='${d}' fill='${color}' fill-opacity='${opacity}'/></svg>`,
  ).replace(/'/g, "%27")}")`

let css = `/* Generated by scripts/pencil.mjs; edit that, not this. */\n`
for (const theme of ["light", "dark"]) {
  const color = oklchToHex(CINNABAR[theme])
  SEEDS.forEach((seed, i) => {
    const sel = theme === "light" ? `[data-pen="${i}"]` : `.dark [data-pen="${i}"]`
    css += `${sel}{--pen:${uri(path(seed, 1), color, 0.9)};--pen-hover:${uri(path(seed, 1.35), color, 1)}}\n`
  })
}
// Loops: the editor's circle around a chosen word, used for the selected sort and tags.
// An open ellipse drawn as one stroke that overruns its start a little and drifts outward
// as it goes, the way a hand closes a circle; slightly tilted, its radius wavering. The
// stroke keeps its width however the loop is stretched (vector-effect: non-scaling-stroke).
const LOOP_SEEDS = [7, 19, 42]
function loop(seed) {
  const r = random(seed)
  const start = -2.2 + r() * 0.6 // radians; starts upper left
  const sweep = Math.PI * 2 + 0.35 + r() * 0.25 // overruns the start
  const tilt = (-4 + r() * 3) * (Math.PI / 180)
  const phase = r() * 6.28
  const pts = []
  for (let i = 0; i <= 64; i++) {
    const u = i / 64
    const t = start + sweep * u
    const grow = 1 - 0.07 + 0.07 * u * 2 // starts a touch inside, ends a touch outside
    const wob = 1 + 0.025 * Math.sin(3 * t + phase)
    const x = 47 * Math.cos(t) * grow * wob
    const y = 40 * Math.sin(t) * grow * wob
    pts.push(`${(50 + x * Math.cos(tilt) - y * Math.sin(tilt)).toFixed(1)} ${(50 + x * Math.sin(tilt) + y * Math.cos(tilt)).toFixed(1)}`)
  }
  return `M${pts.join("L")}`
}
const loopUri = (d, color) =>
  `url("data:image/svg+xml,${encodeURIComponent(
    `<svg xmlns='http://www.w3.org/2000/svg' viewBox='-6 -6 112 112' preserveAspectRatio='none'><path d='${d}' fill='none' stroke='${color}' stroke-width='1.4' stroke-linecap='round' stroke-linejoin='round' vector-effect='non-scaling-stroke'/></svg>`,
  ).replace(/'/g, "%27")}")`
for (const theme of ["light", "dark"]) {
  const color = oklchToHex(CINNABAR[theme])
  LOOP_SEEDS.forEach((seed, i) => {
    const sel = theme === "light" ? `[data-loop="${i}"]` : `.dark [data-loop="${i}"]`
    css += `${sel}{--loop:${loopUri(loop(seed), color)}}\n`
  })
}

writeFileSync(new URL("../app/pencil.css", import.meta.url), css)
console.log(`app/pencil.css: ${SEEDS.length} strokes and ${LOOP_SEEDS.length} loops × 2 themes, ${css.length} bytes`)
